PYTHON_BEST_PRACTICES = """

## 函数设计原则
- 单一职责：每个函数只做一件事。如果函数名里出现"和"字（如 calculate_and_save），拆成两个函数
- 参数不超过 5 个：超过 5 个参数时考虑用 dataclass 或 TypedDict 封装
- 类型注解：所有公共函数必须加类型注解，使用 typing 模块（Python 3.10+ 可用 list/dict 替代 List/Dict）
- 不要用可变对象做默认参数：def foo(items=[]) 是经典 bug，用 def foo(items=None)

## 错误处理
- 永远不要用 except Exception: pass 吞掉异常，至少要打日志
- 外部调用（API、文件、DB）必须 try/except，给出有意义的错误信息
- 自定义异常类继承 Exception 而非 BaseException
- 不要用 assert 做参数校验（-O 模式下 assert 会被跳过），用 if/raise ValueError

## 代码组织
- 一个模块不超过 500 行，超过就要拆
- import 顺序：标准库 → 第三方 → 本地模块，每组之间空一行
- 不要在模块级别执行有副作用的代码（如 print、网络请求），放到 main() 或 if __name__ == "__main__" 里

## 性能
- 循环内不要重复创建正则对象，提到循环外用 re.compile()
- 大列表去重用 set() 而非 list 遍历
- 字符串拼接超过 5 个用 join() 而非 +
- 文件操作用 with 语句确保关闭

## Python 常见坑
- 默认参数只求值一次：def f(x, l=[]) 中 l 在所有调用间共享
- 浅拷贝：list.copy() 和 dict.copy() 是浅拷贝，嵌套对象用 copy.deepcopy()
- 闭包变量绑定：循环中创建的 lambda 都绑定同一个变量，用 functools.partial 或默认参数解决
- 可变对象作为类属性会所有实例共享，应该写在 __init__ 里
- f-string 里不要放复杂表达式，提前计算赋值给变量

## GUI 开发
- tkinter: 所有 GUI 组件必须在主线程创建和操作
- 用 tkinter.StringVar/DoubleVar 做数据绑定
- 页面布局先用 Frame 分区再用 pack/grid，不要一层全铺
- 长时间操作要用 threading 或 after()，避免阻塞主线程导致界面卡死
"""

print("喂 Python 最佳实践...")
