TESTING_KNOWLEDGE = """

## 测试用例设计
- 等价类划分：把输入分成有效等价类和无效等价类，每类至少一个用例
- 边界值：0、空字符串、空列表、None、最大值、最小值
- 正常路径：至少一个 happy path 用例验证核心功能
- 异常路径：非法输入、网络失败、文件不存在、权限不足

## 功能测试 checklist
- 是否所有功能清单项都有对应的测试
- 是否有回归测试（修过的 bug 不再出现）
- 测试输出是否与预期一致（不只看退出码，还要检查实际输出内容）
- 是否在 Python 3.10 / 3.11 / 3.12 环境都能跑

## 常见 bug 模式
- 字符串比较大小写问题：统一用 .lower() 后再比较
- 浮点数比较：不要用 ==，用 abs(a-b) < 1e-9
- 文件操作没有关闭：确认代码中所有 open() 都用了 with
- 空输入：空字符串、空列表、None 输入会导致什么
- 编码问题：非 ASCII 字符（中文、emoji）输出是否正常

## 测试报告格式
- 概述：任务名称、测试日期、总体结论（通过/不通过）
- 逐项验证：每个功能点的测试方法、预期结果、实际结果、是否通过
- Bug 详情：复现步骤、预期行为、实际行为、严重程度
- 改进建议：具体可操作的优化方案，而非泛泛而谈

## 运行测试的步骤
- 先检查代码文件是否存在
- 先静态检查代码（import 是否正常、语法是否有错）
- 再运行代码看退出码和输出
- 针对输出做内容级验证，而非仅看退出码
"""

